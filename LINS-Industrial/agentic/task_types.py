@dataclass
class TaskAnalysis:
    """
    Output of TaskAnalyzer - a rich semantic description.

    REDESIGNED: Instead of only returning a task label, this now carries
    a comprehensive semantic description that directly influences all
    downstream modules.

    These fields are GENERATED by the LLM, not hardcoded.

    Attributes:
        task: The classified task type
        confidence: Confidence score (0.0 - 1.0)
        reasoning: Brief reasoning for the classification
        reasoning_complexity: "low", "medium", or "high"
        requires_multi_source: Whether the answer needs multiple evidence sources
        requires_formula: Whether formulas/calculations are needed
        requires_step_reasoning: Whether step-by-step reasoning is needed
        preferred_source: Preferred knowledge source type
        expected_evidence: What type of evidence is expected
        original_question: The original question
        format: The question format / 题型 ("QA", "FillBlank", "MultipleChoice",
                "Calculation"); normalized from the dataset `_format` truth value.
    """
    task: TaskType = TaskType.GENERAL
    confidence: float = 0.0
    reasoning: str = ""
    format: str = ""  # 题型 (题目形式) — 存 CSV `_format` 真值归一化后的标准枚举
    # Rich semantic fields
    reasoning_complexity: str = "medium"  # "low", "medium", "high"
    requires_multi_source: bool = True
    requires_formula: bool = False
    requires_step_reasoning: bool = False
    preferred_source: str = "standard"  # "standard", "manual", "specification", "general"
    expected_evidence: str = "general"  # "comparison", "symptom", "specification", "formula", "procedure", "general"
    original_question: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "task": self.task.value,
            "confidence": round(self.confidence, 4),
            "reasoning": self.reasoning,
            "format": self.format,
            "reasoning_complexity": self.reasoning_complexity,
            "requires_multi_source": self.requires_multi_source,
            "requires_formula": self.requires_formula,
            "requires_step_reasoning": self.requires_step_reasoning,
            "preferred_source": self.preferred_source,
            "expected_evidence": self.expected_evidence,
            "original_question": self.original_question[:100] if self.original_question else "",
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any], question: str = "") -> "TaskAnalysis":
        """Create from dict (with fallbacks for missing fields)."""
        task_str = data.get("task", "general")
        try:
            task = TaskType(task_str)
        except ValueError:
            task = TaskType.GENERAL

        return cls(
            task=task,
            confidence=float(data.get("confidence", 0.0)),
            reasoning=str(data.get("reasoning", "")),
            reasoning_complexity=str(data.get("reasoning_complexity", "medium")),
            requires_multi_source=bool(data.get("requires_multi_source", True)),
            requires_formula=bool(data.get("requires_formula", False)),
            requires_step_reasoning=bool(data.get("requires_step_reasoning", False)),
            preferred_source=str(data.get("preferred_source", "standard")),
            expected_evidence=str(data.get("expected_evidence", "general")),
            original_question=question,
            format=normalize_format(data.get("format", ""), question),
        )


