@dataclass
class ExecutionDirective:
    """
    A directive from the execution plan instructing a module HOW to execute.

    Organizer and Solver both consume ExecutionDirective objects.
    These are typically extracted from ExecutionGraph node params.

    Attributes:
        module: Which module this directive targets ("organization", "reasoning", "retrieval")
        action: The specific action to execute
        params: Parameters for the action
    """
    module: str = ""
    action: str = ""
    params: Dict[str, Any] = field(default_factory=dict)

    @classmethod
    def from_params(cls, action: str = "", params: Optional[Dict[str, Any]] = None,
                    module: str = "") -> "ExecutionDirective":
        """Create directive from action + params (convenience constructor)."""
        return cls(module=module, action=action, params=params or {})


