@dataclass
class OrganizedEvidence:
    """
    Cleaned, deduplicated, ranked, and task-aware grouped evidence.

    Enhanced: Now supports task-specific grouping strategies.
    The groups can be organized by compared-objects, symptoms,
    candidates, formulas, or chronological order depending on the task.

    Attributes:
        documents: Ranked list of evidence documents
        groups: Evidence grouped by task-specific strategy
        merged_ids: IDs of chunks that were merged
        preserved_citations: List of citation IDs that were preserved
        original_count: Number of documents before organization
        organized_count: Number of documents after organization
        organization_method: How the evidence was organized
    """
    documents: List[Any] = field(default_factory=list)
    groups: Dict[str, List[Any]] = field(default_factory=dict)
    merged_ids: List[str] = field(default_factory=list)
    preserved_citations: List[str] = field(default_factory=list)
    original_count: int = 0
    organized_count: int = 0
    organization_method: str = "topic"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "original_count": self.original_count,
            "organized_count": self.organized_count,
            "num_groups": len(self.groups),
            "group_names": list(self.groups.keys()),
            "merged_chunks": len(self.merged_ids),
            "citations_preserved": len(self.preserved_citations),
            "organization_method": self.organization_method,
        }

    def get_all_documents(self) -> List[Any]:
        """
        Get ALL original documents regardless of group pruning.

        IMPORTANT (Recall-Safe Fix):
            Groups may be pruned by `_select_top_groups` (e.g. keep only 2-3
            groups). If we only read documents from `groups`, any chunk in a
            pruned group would be silently dropped from the final prompt —
            even though the Retriever had hit it and `self.documents` still
            holds it. Always read from the FULL `self.documents` list so that
            Grouping is only a *view*, never a *lossy filter*.
        """
        return list(self.documents)

    def get_context(self, separator: str = "\n---\n") -> str:
        """
        Build context string for LLM prompt preserving the full original chunks.

        Recall-Safe Design:
            - EVERY deduplicated original chunk in `self.documents` is emitted
              verbatim (no summary, no compression).
            - Group names (if any) are emitted as light headers INLINE, purely
              as a readability aid — they DO NOT drop any document.
            - Covers groups pruning: documents that fall into pruned groups
              are still emitted under a trailing "other evidence" header.
        """
        parts = []

        if self.groups:
            # Grouping is a VIEW, never a lossy filter: we still iterate over
            # EVERY document in self.documents (deduplicated originals), so
            # chunks whose group was pruned are NOT lost — they fall through to
            # the "other evidence" header. Group names are emitted INLINE purely
            # as a readability aid and never drop any original chunk.
            doc_to_group: Dict[int, str] = {}
            for group_name, docs in self.groups.items():
                for doc in docs:
                    doc_to_group[id(doc)] = group_name

            for doc in self.documents:
                rank = getattr(doc, "rank", 0)
                score = getattr(doc, "score", 0.0)
                content = getattr(doc, "content", "")
                citation = getattr(doc, "citation", f"[{rank}]")
                group_name = doc_to_group.get(id(doc))
                header = f"## [{group_name}]" if group_name else "## [other evidence]"
                parts.append(
                    f"\n{header}\n"
                    f"{citation} (score={score:.3f})\n{content}"
                )
        else:
            # No grouping — flat full list of every original chunk.
            for doc in self.documents:
                rank = getattr(doc, "rank", 0)
                score = getattr(doc, "score", 0.0)
                industry = getattr(doc, "industry", "")
                capability = getattr(doc, "capability", "")
                content = getattr(doc, "content", "")
                citation = getattr(doc, "citation", f"[{rank}]")
                parts.append(
                    f"{citation} (score={score:.3f}) [{industry}/{capability}]\n{content}"
                )

        context = separator.join(parts) if parts else ""
        return context





