"""
task_types.py: Core type definitions for Agentic RAG v2 (ExecutionGraph).

Defines the task taxonomy and the ExecutionGraph that drives ALL downstream
modules via a topologically-sorted directed graph of workflow nodes.

Architecture v2:
    TaskAnalyzer → TaskAnalysis → StrategyPlanner → ExecutionGraph
                                                          |
                +------------------------------------------+------------------+
                |          |          |           |             |             |
          RetrieveNode  OrganizeNode  DecideNode  MergeNode  ReasonNode  VerifyNode
                |          |          |           |             |             |
                +------------------------------------------+------------------+
                                                          |
                                                      DeepSeek
                                                         |
                                                      Answer

Key Design (v2):
    - ExecutionGraph replaces flat ExecutionPlan
    - Each node is typed: "retrieve" | "organize" | "reason" | "decide" | "merge" | "verify"
    - Nodes form a directed graph with next[] and branches{}
    - Pipeline = GraphExecutor that topologically walks the graph
    - Supports: sequential, parallel branches, conditional branching, multi-hop retrieval
    - Each adaptive component is independently measurable for ablation
"""

from dataclasses import dataclass, field
from typing import List, Dict, Optional, Any
from enum import Enum


class TaskType(str, Enum):
    """
    Industry-domain reasoning task types.

    These are NOT question formats (QA / FillBlank / MultipleChoice).
    They describe the reasoning task required to answer the question.
    """
    COMPARISON = "comparison"
    DIAGNOSIS = "diagnosis"
    SELECTION = "selection"
    CALCULATION = "calculation"
    STANDARD_INTERPRETATION = "standard_interpretation"
    PROCEDURE = "procedure"
    EXPLANATION = "explanation"
    GENERAL = "general"


# ============================================================
# Question Format (题型) — 独立于 TaskType 的"题目形式"维度
# ============================================================
# 数据集 CSV `_format` 列即"题型"真值标签（非 TaskType 推理任务类型）。
# 方案B：TaskAnalysis 新增 `format` 字段存 `_format` 真值(归一化)作为"题型"，
#   保留 task(8类推理任务) 不变。IndustryBench 该列仅 4 个取值。

QUESTION_FORMATS = ["QA", "FillBlank", "MultipleChoice", "Calculation"]

# 中文 `_format` 标签 → 英文题型枚举
CN2EN_FORMAT = {
    "问答题": "QA",
    "填空题": "FillBlank",
    "选择题": "MultipleChoice",
    "计算题": "Calculation",
    "问答": "QA",
    "填空": "FillBlank",
    "选择": "MultipleChoice",
    "计算": "Calculation",
}


def infer_format_heuristic(question: str) -> str:
    """
    No-`_format` fallback: heuristically pick a standard 题型.
    Returns one of QUESTION_FORMATS.
    """
    q = (question or "").strip()
    if any(b in q for b in ["___", "____", "＿", "___?"]):
        return "FillBlank"
    head = q[:20]
    if any(tok in head for tok in ["A.", "A、", "A)", "A．", "B.", "B、", "C.", "C、", "D."]):
        return "MultipleChoice"
    if any(kw in head for kw in ["计算", "多少", "数值", "为多少", "多大", "电压", "电流",
                                  "功率", "mm", "kW", "Hz", "kg", "℃"]):
        return "Calculation"
    return "QA"


def normalize_format(q_fmt, question: str = "") -> str:
    """
    Normalize any incoming 题型 value (Chinese label / English enum / empty)
    to one of QUESTION_FORMATS. Falls back to infer_format_heuristic(question).
    """
    if q_fmt is None:
        q_fmt = ""
    s = str(q_fmt).strip()
    if s in QUESTION_FORMATS:
        return s
    if s in CN2EN_FORMAT:
        return CN2EN_FORMAT[s]
    lowered = s.lower().replace("_", "").replace(" ", "")
    alias = {
        "qa": "QA", "fillblank": "FillBlank", "blank": "FillBlank",
        "multiplechoice": "MultipleChoice", "choice": "MultipleChoice",
        "selection": "MultipleChoice", "calculation": "Calculation",
        "calc": "Calculation", "math": "Calculation",
    }
    if lowered in alias:
        return alias[lowered]
    # 无法识别或为空 → 启发式兜底
    return infer_format_heuristic(question)


