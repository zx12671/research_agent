GRAPH_NODE_TYPES = {
    "retrieve",   # Retrieve evidence from knowledge base
    "organize",   # Organize/group evidence
    "reason",     # Reasoning step (LLM call)
    "decide",     # Conditional decision (branch)
    "merge",      # Merge multiple evidence streams
    "verify",     # Verify/validate answer
    "end",        # Terminal node
}

GRAPH_NODE_TYPES_LIST = sorted(GRAPH_NODE_TYPES)


@dataclass
class GraphNode:
    """
    A single node in the ExecutionGraph workflow.

    Each node is typed and carries its own params. Nodes are connected
    via `next` (sequential successors) and `branches` (conditional).

    Node Types:
        retrieve  → Execute retrieval operation
        organize  → Organize/group evidence
        reason    → Execute reasoning step (LLM call)
        decide    → Conditional branch based on a condition
        merge     → Merge multiple evidence streams into one
        verify    → Verify/validate step with pass/fail branches
        end       → Terminal node (graph execution ends here)

    Attributes:
        id: Unique node identifier (e.g., "retrieve_1", "decide_sufficient")
        type: Node type from GRAPH_NODE_TYPES
        action: Specific action for this node
        params: Parameters for this node's action
        next: List of successor node IDs (sequential flow)
        branches: Conditional branches {condition: node_id}
                  e.g., {"sufficient": "reason_1", "insufficient": "retrieve_2"}
        fallback: Fallback node ID if primary path fails
        description: Human-readable description of this node's purpose
    """
    id: str
    type: str                           # "retrieve" | "organize" | "reason" | "decide" | "merge" | "verify" | "end"
    action: str = ""                    # e.g., "semantic_search", "group_by_comparison", "compare_step"
    params: Dict[str, Any] = field(default_factory=dict)
    next: List[str] = field(default_factory=list)
    branches: Dict[str, str] = field(default_factory=dict)
    fallback: Optional[str] = None
    description: str = ""

    def __post_init__(self):
        """Validate node type."""
        if self.type not in GRAPH_NODE_TYPES:
            valid = ", ".join(GRAPH_NODE_TYPES_LIST)
            raise ValueError(f"Unknown node type '{self.type}'. Valid types: {valid}")

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "type": self.type,
            "action": self.action,
            "params": {k: str(v)[:80] if not isinstance(v, (int, float, bool)) else v
                       for k, v in self.params.items()},
            "next": self.next,
            "branches": self.branches,
            "fallback": self.fallback,
            "description": self.description[:120] if self.description else "",
        }


@dataclass
class ExecutionGraph:
    """
    A directed graph of workflow nodes — the output of StrategyPlanner v2.

    THIS replaces ExecutionPlan. Instead of a flat list of independent
    directives, ExecutionGraph defines a true multi-step workflow with:

        • Sequential Chains:    retrieve → organize → reason
        • Conditional Branching:  Is evidence sufficient? → Yes/No
        • Multi-hop Retrieval:   retrieve → decide → retrieve_again → merge
        • Verification Loops:    reason → verify → (pass→end | fail→retry)
        • Parallel Streams:      retrieve_A ──→ merge ──→ reason
                                  retrieve_B ──→

    Architecture:
        StrategyPlanner (v2) → ExecutionGraph → GraphExecutor → Answer

    The GraphExecutor walks the graph topologically, dispatching each node
    to the appropriate module based on node.type.

    IMPORTANT: Downstream modules (EvidenceOrganizer, TaskSolver) consume
    ExecutionDirective objects extracted from node params via get_instruction().

    Attributes:
        task: The classified task type
        task_analysis: The full rich semantic description from TaskAnalyzer
        nodes: Dict of {node_id: GraphNode} — the actual graph structure
        entry_points: Ordered list of entry node IDs (graph can have multiple starts)
        task_specific_hints: Additional natural language instructions
    """
    task: TaskType = TaskType.GENERAL
    task_analysis: Optional[TaskAnalysis] = None
    nodes: Dict[str, GraphNode] = field(default_factory=dict)
    entry_points: List[str] = field(default_factory=list)
    task_specific_hints: str = ""

    # ──────────────────────────────────────────────
    # Graph topology helpers
    # ──────────────────────────────────────────────

    def get_node(self, node_id: str) -> Optional[GraphNode]:
        """Get a node by ID."""
        return self.nodes.get(node_id)

    def get_nodes_by_type(self, node_type: str) -> List[GraphNode]:
        """Get all nodes of a given type."""
        return [n for n in self.nodes.values() if n.type == node_type]

    def get_entry_nodes(self) -> List[GraphNode]:
        """Get the entry point node(s) of the graph."""
        return [self.nodes[eid] for eid in self.entry_points if eid in self.nodes]

    def get_successors(self, node: GraphNode) -> List[GraphNode]:
        """Get successor nodes (sequential next)."""
        return [self.nodes[nid] for nid in node.next if nid in self.nodes]

    def get_first_node_of_type(self, node_type: str) -> Optional[GraphNode]:
        """Get the first node of a given type (in topological order)."""
        ordered = self.topological_sort()
        for n in ordered:
            if n.type == node_type:
                return n
        return None

    def get_instruction(self, module: str) -> Optional["ExecutionDirective"]:
        """
        Get an ExecutionDirective for a specific downstream module.

        This is the bridge between ExecutionGraph and downstream components.
        Each module type corresponds to a node type:
            - "organization" → first "organize" node
            - "reasoning"    → first "reason" node
            - "retrieval"    → first "retrieve" node

        Args:
            module: Module name ("organization", "reasoning", "retrieval")

        Returns:
            ExecutionDirective with action + params, or None if not found
        """
        node_type_map = {
            "organization": "organize",
            "reasoning": "reason",
            "retrieval": "retrieve",
        }
        ntype = node_type_map.get(module)
        if not ntype:
            return None

        node = self.get_first_node_of_type(ntype)
        if not node:
            return None

        return ExecutionDirective(
            module=module,
            action=node.action,
            params=node.params,
        )

    def topological_sort(self) -> List[GraphNode]:
        """
        Return nodes in topological order (BFS from entry points).
        This determines the execution order.
        """
        visited: set = set()
        ordered: List[GraphNode] = []

        def bfs(start_ids: List[str]) -> None:
            queue = list(start_ids)
            while queue:
                nid = queue.pop(0)
                if nid in visited:
                    continue
                visited.add(nid)
                node = self.nodes.get(nid)
                if node:
                    ordered.append(node)
                    # Add next nodes
                    for next_id in node.next:
                        if next_id not in visited:
                            queue.append(next_id)
                    # Add branch targets
                    for branch_id in node.branches.values():
                        if branch_id not in visited and branch_id in self.nodes:
                            queue.append(branch_id)
                    # Add fallback
                    if node.fallback and node.fallback not in visited:
                        queue.append(node.fallback)

        bfs(self.entry_points)
        return ordered

    def contains_type(self, node_type: str) -> bool:
        """Check if the graph contains any node of the given type."""
        return any(n.type == node_type for n in self.nodes.values())

    def to_dict(self) -> Dict[str, Any]:
        return {
            "task": self.task.value if self.task else "unknown",
            "num_nodes": len(self.nodes),
            "entry_points": self.entry_points,
            "node_types": list(set(n.type for n in self.nodes.values())),
            "node_summary": {
                nid: n.type for nid, n in self.nodes.items()
            },
            "has_conditional_branching": any(
                len(n.branches) > 0 for n in self.nodes.values()
            ),
            "has_multi_hop_retrieval": len(self.get_nodes_by_type("retrieve")) > 1,
            "has_verification": self.contains_type("verify"),
            "task_specific_hints": self.task_specific_hints[:200] if self.task_specific_hints else "",
        }

    def visualize(self) -> str:
        """
        Simple ASCII visualization of the graph.
        """
        lines = [f"ExecutionGraph: {self.task.value if self.task else '?'}"]
        lines.append(f"  Nodes: {len(self.nodes)}, Entry: {self.entry_points}")
        lines.append("")

        ordered = self.topological_sort()
        for node in ordered:
            indent = "  "

            # Node header
            branches_str = ""
            if node.branches:
                branches_str = f" ──branch──> {list(node.branches.values())}"
            next_str = ""
            if node.next:
                next_str = f" ──> {node.next}"
            fallback_str = ""
            if node.fallback:
                fallback_str = f" [fallback: {node.fallback}]"

            dash = "●" if node.id in self.entry_points else "○"
            lines.append(f"{indent}{dash} [{node.type}] {node.id}: {node.action}{next_str}{branches_str}{fallback_str}")

            if node.params:
                for k, v in list(node.params.items())[:5]:
                    lines.append(f"{indent}  {k}: {v}")

        return "\n".join(lines)


